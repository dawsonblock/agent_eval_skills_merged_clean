_JSON_SCHEMA_VALIDATOR_CODE = '''\
"""
JSON Schema Validator — validates JSON data files against a JSON Schema file.

Generated by ToolForge.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path


def run(data_path: str, schema_path: str, output_path: str | None = None) -> dict:
    try:
        import jsonschema  # noqa: PLC0415
    except ImportError as exc:
        raise RuntimeError(
            "jsonschema package is required. Install with: pip install jsonschema"
        ) from exc

    data_file = Path(data_path)
    schema_file = Path(schema_path)
    report_file = Path(output_path) if output_path else Path("outputs") / "validation_report.json"

    if data_file.suffix.lower() != ".json":
        raise ValueError("data_path must point to a .json file")
    if schema_file.suffix.lower() != ".json":
        raise ValueError("schema_path must point to a .json file")
    if not data_file.exists():
        raise FileNotFoundError(f"Data file not found: {data_path}")
    if not schema_file.exists():
        raise FileNotFoundError(f"Schema file not found: {schema_path}")

    data = json.loads(data_file.read_text(encoding="utf-8"))
    schema = json.loads(schema_file.read_text(encoding="utf-8"))

    validator = jsonschema.Draft7Validator(schema)
    errors = [
        {
            "path": ".".join(str(p) for p in err.path) if err.path else "$",
            "message": err.message,
        }
        for err in sorted(validator.iter_errors(data), key=lambda e: str(e.path))
    ]
    valid = len(errors) == 0

    report_file.parent.mkdir(parents=True, exist_ok=True)
    report = {
        "valid": valid,
        "error_count": len(errors),
        "errors": errors,
    }
    report_file.write_text(json.dumps(report, indent=2), encoding="utf-8")

    return {
        "valid": valid,
        "error_count": len(errors),
        "report_path": str(report_file),
    }


if __name__ == "__main__":
    raw = os.environ.get("TOOLFORGE_INPUTS")
    if not raw:
        print(json.dumps({"error": "TOOLFORGE_INPUTS is required"}), file=sys.stderr)
        raise SystemExit(2)
    try:
        inputs = json.loads(raw)
        result = run(**inputs)
        print(json.dumps(result, indent=2, sort_keys=True))
    except Exception as exc:  # noqa: BLE001
        print(
            json.dumps({"error": str(exc), "type": exc.__class__.__name__}),
            file=sys.stderr,
        )
        raise SystemExit(1)
'''

_LOCAL_FILE_HASHER_CODE = '''\
"""
Local File Hasher — computes deterministic hashes for local files.

Generated by ToolForge.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from pathlib import Path

_SUPPORTED = {"md5", "sha256", "sha512"}


def run(file_path: str, algorithm: str = "sha256", output_path: str | None = None) -> dict:
    source = Path(file_path)
    if not source.exists():
        raise FileNotFoundError(f"File not found: {file_path}")

    alg = algorithm.strip().lower()
    if alg not in _SUPPORTED:
        raise ValueError(f"Unsupported algorithm '{algorithm}'. Allowed: {', '.join(sorted(_SUPPORTED))}")

    digest = hashlib.new(alg)
    with source.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 64), b""):
            digest.update(chunk)

    result = {
        "file": str(source),
        "algorithm": alg,
        "hash": digest.hexdigest(),
        "size_bytes": source.stat().st_size,
    }

    if output_path:
        out = Path(output_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(result, indent=2), encoding="utf-8")
        result["report_path"] = str(out)

    return result


if __name__ == "__main__":
    raw = os.environ.get("TOOLFORGE_INPUTS")
    if not raw:
        print(json.dumps({"error": "TOOLFORGE_INPUTS is required"}), file=sys.stderr)
        raise SystemExit(2)
    try:
        inputs = json.loads(raw)
        result = run(**inputs)
        print(json.dumps(result, indent=2, sort_keys=True))
    except Exception as exc:  # noqa: BLE001
        print(
            json.dumps({"error": str(exc), "type": exc.__class__.__name__}),
            file=sys.stderr,
        )
        raise SystemExit(1)
'''

