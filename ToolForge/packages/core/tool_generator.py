def _ctx(spec: ToolSpec) -> dict[str, Any]:
    type_map = {"string": "str", "number": "float", "integer": "int",
                "boolean": "bool", "array": "list", "object": "dict"}
    output_type = type_map.get(spec.output.type, "Any")
    return {
        "spec": spec,
        "toolforge_version": TOOLFORGE_VERSION,
        "output_type": output_type,
    }


def scaffold_tool(spec: ToolSpec, output_root: Path, overwrite: bool = False) -> list[Path]:
    """
    Scaffold a tool directory at *output_root/{spec.slug}/*.
    Returns list of written file paths.
    """
    tool_dir = output_root / spec.slug
    tool_dir.mkdir(parents=True, exist_ok=True)
    (tool_dir / "tests").mkdir(exist_ok=True)
    (tool_dir / "examples").mkdir(exist_ok=True)

    ctx = _ctx(spec)
    written: list[Path] = []

    # --- toolforge.yaml ---
    spec_path = tool_dir / "toolforge.yaml"
    if not spec_path.exists() or overwrite:
        spec.to_yaml(spec_path)
        written.append(spec_path)

    # --- tool.py (implementation stub or working code) ---
    tool_py = tool_dir / "tool.py"
    if spec.slug == "csv-cleaner":
        content = _CSV_CLEANER_CODE
    elif spec.slug == "json-schema-validator":
        content = _JSON_SCHEMA_VALIDATOR_CODE
    elif spec.slug == "local-file-hasher":
        content = _LOCAL_FILE_HASHER_CODE
    else:
        content = render_template("mcp_server_python", "tool.py.j2", ctx)
    if write_rendered(tool_py, content, overwrite):
        written.append(tool_py)

    # --- README.md ---
    readme = tool_dir / "README.md"
    content = render_template("readme_template", "README.md.j2", ctx)
    if write_rendered(readme, content, overwrite):
        written.append(readme)

    # --- tests/test_{slug}.py ---
    test_py = tool_dir / "tests" / f"test_{spec.slug.replace('-', '_')}.py"
    test_content = _generate_test(spec)
    if write_rendered(test_py, test_content, overwrite):
        written.append(test_py)

    if spec.slug == "csv-cleaner":
        examples_dir = tool_dir / "examples"
        outputs_dir = tool_dir / "outputs"
        examples_dir.mkdir(exist_ok=True)
        outputs_dir.mkdir(exist_ok=True)

        input_csv = examples_dir / "input.csv"
        if not input_csv.exists() or overwrite:
            input_csv.write_text(_CSV_EXAMPLE_INPUT, encoding="utf-8")
            written.append(input_csv)

        empty_csv = examples_dir / "empty.csv"
        if not empty_csv.exists() or overwrite:
            empty_csv.write_text("", encoding="utf-8")
            written.append(empty_csv)

    if spec.slug == "json-schema-validator":
        examples_dir = tool_dir / "examples"
        outputs_dir = tool_dir / "outputs"
        examples_dir.mkdir(exist_ok=True)
        outputs_dir.mkdir(exist_ok=True)

        schema_json = examples_dir / "schema.json"
        if not schema_json.exists() or overwrite:
            schema_json.write_text(_JSON_SCHEMA_VALIDATOR_SCHEMA, encoding="utf-8")
            written.append(schema_json)

        valid_json = examples_dir / "data_valid.json"
        if not valid_json.exists() or overwrite:
            valid_json.write_text(_JSON_SCHEMA_VALIDATOR_VALID, encoding="utf-8")
            written.append(valid_json)

        invalid_json = examples_dir / "data_invalid.json"
        if not invalid_json.exists() or overwrite:
            invalid_json.write_text(_JSON_SCHEMA_VALIDATOR_INVALID, encoding="utf-8")
            written.append(invalid_json)

    if spec.slug == "local-file-hasher":
        examples_dir = tool_dir / "examples"
        outputs_dir = tool_dir / "outputs"
        examples_dir.mkdir(exist_ok=True)
        outputs_dir.mkdir(exist_ok=True)

        sample_txt = examples_dir / "sample.txt"
        if not sample_txt.exists() or overwrite:
            sample_txt.write_text(_LOCAL_FILE_HASHER_SAMPLE, encoding="utf-8")
            written.append(sample_txt)

    return written


def _generate_test(spec: ToolSpec) -> str:
    """Generate a minimal pytest test file for the tool."""
    if spec.slug == "csv-cleaner":
        return _generate_csv_cleaner_tests()
    if spec.slug == "json-schema-validator":
        return _generate_json_schema_validator_tests()
    if spec.slug == "local-file-hasher":
        return _generate_local_file_hasher_tests()

    slug_id = spec.slug.replace("-", "_")
    lines = [
        "\"\"\"",
        f"Auto-generated tests for {spec.slug}.",
        "\"\"\"",
        "import pytest",
        "import sys",
        "from pathlib import Path",
        "",
        "sys.path.insert(0, str(Path(__file__).parent.parent))",
        "from tool import run",
        "",
    ]
    if spec.eval.cases:
        for case in spec.eval.cases:
            fn = f"test_{slug_id}_{case.id.replace('-', '_').replace(' ', '_')}"
            lines.append(f"def {fn}():")
            lines.append(f'    """Eval case: {case.description or case.id}"""')
            kw = ", ".join(f"{k}={v!r}" for k, v in case.inputs.items())
            lines.append("    try:")
            lines.append(f"        result = run({kw})")
            lines.append("    except NotImplementedError:")
            lines.append("        pytest.skip(\"Tool implementation is pending\")")
            if case.expected_output is not None:
                lines.append(f"    assert result == {case.expected_output!r}")
            else:
                lines.append("    assert result is not None")
            lines.append("")
    else:
        lines += [
            f"def test_{slug_id}_smoke():",
            '    """Smoke test — ensure run() is importable and raises NotImplementedError."""',
            "    with pytest.raises(NotImplementedError):",
            "        run()",
            "",
        ]
    return "\n".join(lines)


