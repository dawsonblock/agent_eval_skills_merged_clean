# Working implementation for the csv-cleaner tool slug
_CSV_CLEANER_CODE = '''\
"""
CSV Cleaner — normalizes headers, trims cells, and removes empty rows.

Generated by ToolForge.
"""
from __future__ import annotations

import csv
import json
import os
import re
import sys
from pathlib import Path


def normalize_header(value: str) -> str:
    text = re.sub(r"\\s+", "_", (value or "").strip().lower())
    text = text.strip("_")
    return text or "column"


def dedupe_headers(headers: list[str]) -> list[str]:
    seen: dict[str, int] = {}
    output: list[str] = []
    for item in headers:
        base = item or "column"
        count = seen.get(base, 0) + 1
        seen[base] = count
        output.append(base if count == 1 else f"{base}_{count}")
    return output


def run(input_path: str, output_path: str | None = None) -> dict:
    input_file = Path(input_path)
    output_file = Path(output_path) if output_path else Path("outputs") / "cleaned.csv"

    if input_file.suffix.lower() != ".csv":
        raise ValueError("input_path must point to a .csv file")
    if not input_file.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    output_file.parent.mkdir(parents=True, exist_ok=True)

    with input_file.open("r", encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.reader(fh))

    if not rows:
        output_file.write_text("", encoding="utf-8")
        return {
            "cleaned_path": str(output_file),
            "input_rows": 0,
            "output_rows": 0,
            "removed_empty_rows": 0,
            "input_columns": 0,
            "output_columns": 0,
            "headers": [],
        }

    raw_headers = rows[0]
    headers = dedupe_headers([normalize_header(h) for h in raw_headers])
    input_columns = len(raw_headers)

    cleaned_rows: list[list[str]] = []
    removed = 0
    for row in rows[1:]:
        normalized = [cell.strip() for cell in row]
        if len(normalized) < len(headers):
            normalized += [""] * (len(headers) - len(normalized))
        elif len(normalized) > len(headers):
            normalized = normalized[: len(headers)]
        if not any(normalized):
            removed += 1
            continue
        cleaned_rows.append(normalized)

    with output_file.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(headers)
        writer.writerows(cleaned_rows)

    return {
        "cleaned_path": str(output_file),
        "input_rows": max(len(rows) - 1, 0),
        "output_rows": len(cleaned_rows),
        "removed_empty_rows": removed,
        "input_columns": input_columns,
        "output_columns": len(headers),
        "headers": headers,
    }


if __name__ == "__main__":
    raw = os.environ.get("TOOLFORGE_INPUTS")
    if not raw:
        print(json.dumps({"error": "TOOLFORGE_INPUTS is required"}), file=sys.stderr)
        raise SystemExit(2)
    try:
        inputs = json.loads(raw)
        result = run(**inputs)
        print(json.dumps(result, indent=2, sort_keys=True))
    except Exception as exc:  # noqa: BLE001
        print(
            json.dumps({"error": str(exc), "type": exc.__class__.__name__}),
            file=sys.stderr,
        )
        raise SystemExit(1)
'''

