def get_provider(
    provider_name: str,
    **kwargs: Any,
) -> AIProvider:
    """
    Factory function to get an AI provider by name.

    Args:
        provider_name: Name of the provider ("mock", "openai", "anthropic", "ollama", "azure_openai", "local", "deepseek")
        **kwargs: Provider-specific configuration

    Returns:
        An instance of the requested provider

    Raises:
        ValueError: If the provider name is unknown
        ProviderError: If the provider cannot be initialized
    """
    providers: dict[str, type[AIProvider]] = {
        "mock": MockProvider,
        "local": LocalProvider,
        "ollama": OllamaProvider,
        "openai": OpenAIProvider,
        "anthropic": AnthropicProvider,
        "azure_openai": AzureOpenAIProvider,
    }

    # Lazy import DeepSeekProvider to avoid circular import
    if provider_name == "deepseek":
        from packages.ai.providers.deepseek_provider import DeepSeekProvider

        providers["deepseek"] = DeepSeekProvider

    if provider_name not in providers:
        raise ValueError(
            f"Unknown provider: {provider_name!r}. "
            f"Available providers: {sorted(providers.keys())}"
        )

    provider_class = providers[provider_name]
    try:
        return provider_class(**kwargs)
    except Exception as e:
        raise ProviderError(
            f"Failed to initialize provider {provider_name!r}: {e}",
            provider_name=provider_name,
        ) from e


def is_provider_available(provider_name: str) -> bool:
    """
    Check if a provider is available without instantiating it.

    Args:
        provider_name: Name of the provider to check

    Returns:
        True if the provider is available, False otherwise
    """
    try:
        provider = get_provider(provider_name)
        return provider.is_available()
    except (ValueError, ProviderError):
        return False


class OllamaProvider(AIProvider):
    """
    Adapter for OllamaSpecGenerator to AIProvider interface.

    Wraps the existing OllamaSpecGenerator to conform to the AIProvider interface.
    """

    def __init__(
        self,
        model: str = "llama3",
        base_url: str = "http://localhost:11434",
        max_retries: int = 3,
        timeout_seconds: int = 30,
        retry_backoff_seconds: int = 1,
    ) -> None:
        from packages.ai.providers.ollama_generator import OllamaSpecGenerator

        self._generator = OllamaSpecGenerator(
            model=model,
            base_url=base_url,
            max_retries=max_retries,
            timeout_seconds=timeout_seconds,
            retry_backoff_seconds=retry_backoff_seconds,
        )
        self._model = model
        self._base_url = base_url
        self._timeout_seconds = timeout_seconds

    def complete_json(
        self,
        prompt: str,
        system_prompt: str | None = None,
        temperature: float = 0.7,
        max_tokens: int = 2000,
        timeout: int = 30,
    ) -> dict[str, Any]:
        """
        Complete a prompt using Ollama.

        Args:
            prompt: The user prompt
            system_prompt: Ignored (Ollama uses its own system prompt)
            temperature: Ignored (Ollama uses its own settings)
            max_tokens: Ignored (Ollama uses its own settings)
            timeout: Request timeout in seconds

        Returns:
            The ToolSpec as a dict
        """
        spec = self._generator.generate(prompt)
        return spec.model_dump(mode="python", exclude_none=True)

    def is_available(self) -> bool:
        """
        Check if Ollama is available.

        Returns:
            True if Ollama server is reachable, False otherwise
        """
        try:
            import requests  # noqa: PLC0415

            response = requests.get(
                f"{self._base_url}/api/tags",
                timeout=5,
            )
            return response.status_code == 200
        except Exception:
            return False


