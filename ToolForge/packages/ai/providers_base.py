"""
AI Provider Abstraction — unified interface for AI service providers.

This module defines the AIProvider interface and concrete implementations
for various AI services (OpenAI, Anthropic, Ollama, Azure OpenAI, Mock).

IMPORTANT: AI ROLE BOUNDARIES
- All providers return structured data (JSON/dict), never execute code
- MockProvider is used in CI to prevent external API calls
- Providers fail gracefully when unavailable
- No autonomous file writes or command execution
- See ToolForge/docs/AI_ROLE_BOUNDARIES.md for full boundaries
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class AIProvider(ABC):
    """
    Abstract base class for AI service providers.

    All providers must implement the complete_json method which returns
    structured JSON data from the AI service.
    """

    @abstractmethod
    def complete_json(
        self,
        prompt: str,
        system_prompt: str | None = None,
        temperature: float = 0.7,
        max_tokens: int = 2000,
        timeout: int = 30,
    ) -> dict[str, Any]:
        """
        Complete a prompt and return structured JSON output.

        Args:
            prompt: The user prompt to send to the AI
            system_prompt: Optional system prompt for context
            temperature: Sampling temperature (0.0-1.0)
            max_tokens: Maximum tokens to generate
            timeout: Request timeout in seconds

        Returns:
            Parsed JSON/dict response from the AI

        Raises:
            ProviderError: If the request fails or times out
            ValueError: If the response cannot be parsed as JSON
        """
        pass

    @abstractmethod
    def is_available(self) -> bool:
        """
        Check if the provider is available and configured.

        Returns:
            True if the provider can be used, False otherwise
        """
        pass


class ProviderError(Exception):
    """Base exception for provider errors."""

    def __init__(self, message: str, provider_name: str | None = None) -> None:
        self.provider_name = provider_name
        super().__init__(message)


